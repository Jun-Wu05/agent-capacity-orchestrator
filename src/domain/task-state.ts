/**
 * Task 状态与迁移事件（TDD-V0.1 §5.2 / §5.3）。
 *
 * domain 层约束：不依赖 Windows、Codex、本地路径与任何 I/O。
 */
export enum TaskState {
  CAPTURING = "CAPTURING",
  WAITING_CAPACITY = "WAITING_CAPACITY",
  WAITING_SESSION = "WAITING_SESSION",
  READY = "READY",
  PREFLIGHT = "PREFLIGHT",
  RESUMING_SESSION = "RESUMING_SESSION",
  RESUMING_TASK = "RESUMING_TASK",
  RUNNING = "RUNNING",
  TESTING = "TESTING",
  FINALIZING = "FINALIZING",
  COMPLETED = "COMPLETED",
  BLOCKED = "BLOCKED",
  FAILED = "FAILED",
  CANCELLED = "CANCELLED",
}

/**
 * 迁移事件 = §5.3 各迁移边的触发条件。
 *
 * 注意：
 * - TESTING 的三条迁移边在 V0.1 禁用（§5.3 注记），没有任何事件可进入或离开 TESTING；
 * - WAITING_SESSION 没有任何超时事件：转 RESUMING_TASK 只能由用户显式触发
 *   （`aco resume --as-task`），不存在自动超时迁移。
 */
export enum TaskEvent {
  // CAPTURING
  CAPTURE_SUCCEEDED = "CAPTURE_SUCCEEDED",
  CAPTURE_FAILED = "CAPTURE_FAILED",
  // WAITING_CAPACITY
  CAPACITY_ELIGIBLE = "CAPACITY_ELIGIBLE",
  FATAL_ERROR = "FATAL_ERROR",
  CANCEL_REQUESTED = "CANCEL_REQUESTED",
  // READY（start_policy）
  START_AUTO = "START_AUTO",
  START_MANUAL = "START_MANUAL",
  // PREFLIGHT
  PREFLIGHT_PASSED = "PREFLIGHT_PASSED",
  PREFLIGHT_FAILED = "PREFLIGHT_FAILED",
  // RESUMING_SESSION
  SESSION_RESUMED = "SESSION_RESUMED",
  SESSION_LOCKED = "SESSION_LOCKED",
  SESSION_NOT_FOUND_WITH_SNAPSHOT = "SESSION_NOT_FOUND_WITH_SNAPSHOT",
  SESSION_NOT_FOUND_WITHOUT_SNAPSHOT = "SESSION_NOT_FOUND_WITHOUT_SNAPSHOT",
  QUOTA_EXHAUSTED = "QUOTA_EXHAUSTED",
  UNSAFE_RESUME = "UNSAFE_RESUME",
  // WAITING_SESSION
  SESSION_RETRY = "SESSION_RETRY",
  USER_RESUME_AS_TASK = "USER_RESUME_AS_TASK",
  // RESUMING_TASK
  TASK_RESUME_SUCCEEDED = "TASK_RESUME_SUCCEEDED",
  TASK_RESUME_FAILED = "TASK_RESUME_FAILED",
  // RUNNING（每轮结果判定，§8.6 / ADR 0003）
  ROUND_DONE = "ROUND_DONE",
  ROUND_DONE_ESCALATION_DENIED = "ROUND_DONE_ESCALATION_DENIED",
  AGENT_REPORTED_BLOCKED = "AGENT_REPORTED_BLOCKED",
  CONTINUE_NEXT_ROUND = "CONTINUE_NEXT_ROUND",
  TRANSIENT_ERROR = "TRANSIENT_ERROR",
  // FINALIZING
  FINALIZE_SUCCEEDED = "FINALIZE_SUCCEEDED",
  FINALIZE_FAILED = "FINALIZE_FAILED",
}
